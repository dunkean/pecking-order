import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';

const base = process.env.PECKING_ORDER_URL || 'http://127.0.0.1:8773';
const output = path.resolve(import.meta.dirname, '../output/screenshots');
await fs.mkdir(output, { recursive: true });
const edge = process.env.STUDIO_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const executablePath = await fs.access(edge).then(() => edge).catch(() => undefined);
const browser = await chromium.launch({ executablePath, headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const wait = predicate => page.waitForFunction(predicate);
try {
  const glossary = await (await fetch(`${base}/api/glossary`)).json();
  await page.goto(`${base}/glossary`);
  await wait(() => document.querySelector('#entries').getAttribute('aria-busy') === 'false');
  assert.equal(Number(await page.locator('#results-count').getAttribute('data-count')), glossary.counts.terms);
  assert.equal(await page.locator('.glossary-entry').count(), 100);
  await page.screenshot({ path: path.join(output, 'glossary-fr.png') });
  await page.selectOption('#per-page', 'all');
  assert.equal(await page.locator('.glossary-entry').count(), glossary.counts.terms);
  await page.selectOption('#per-page', '100');
  await page.fill('#search', 'Tsar');
  await wait(() => new URL(location.href).searchParams.get('q') === 'Tsar');
  const tsar = page.locator('.glossary-entry[data-term="Tsar"]').first();
  await tsar.locator('summary').click();
  await tsar.locator('.term-detail .system-links a').first().waitFor();
  assert.match(await tsar.locator('.term-detail').innerText(), /Niveau|Importance/);
  await page.screenshot({ path: path.join(output, 'glossary-tsar.png') });
  await tsar.locator('.term-detail .system-links a').first().click();
  await page.waitForURL(url => url.pathname === '/' && url.searchParams.has('system'));
  await wait(() => document.querySelector('#roles')?.textContent.includes('Tsar'));
  await page.goBack();
  await wait(() => document.querySelector('#entries').getAttribute('aria-busy') === 'false');
  assert.equal(await page.locator('#search').inputValue(), 'Tsar');
  await page.click('#reset');
  await page.selectOption('#theme', 'tswana');
  await page.locator('#employment-filters summary').click();
  await page.selectOption('#function', 'village_head');
  assert.ok(await page.locator('.glossary-entry').count() > 0);
  assert.match(await page.locator('#entries').innerText(), /Kgosi/);
  await page.locator('[data-tab="functions"]').click();
  await page.locator('.glossary-entry summary').first().click();
  assert.ok(await page.locator('.term-detail h3').first().innerText());
  await page.click('#reset');
  await page.locator('[data-tab="systems"]').click();
  assert.equal(Number(await page.locator('#results-count').getAttribute('data-count')), glossary.counts.systems);
  await page.locator('[data-tab="powers"]').click();
  assert.equal(Number(await page.locator('#results-count').getAttribute('data-count')), glossary.counts.powers);
  await page.locator('[data-tab="titles"]').click();
  await page.fill('#search', 'Reine');
  await wait(() => new URL(location.href).searchParams.get('q') === 'Reine');
  assert.ok(await page.locator('.form-tag').count() > 0);
  const csvEvent = page.waitForEvent('download');
  await page.click('#export-csv');
  const csv = await csvEvent;
  await csv.saveAs(path.join(output, 'glossary-selection.csv'));
  assert.match(await fs.readFile(path.join(output, 'glossary-selection.csv'), 'utf8'), /Reine/);
  await page.click('#reset');
  const jsonEvent = page.waitForEvent('download');
  await page.click('#download-all');
  const jsonDownload = await jsonEvent;
  await jsonDownload.saveAs(path.join(output, 'glossary-full.json'));
  const downloaded = JSON.parse(await fs.readFile(path.join(output, 'glossary-full.json'), 'utf8'));
  assert.equal(downloaded.terms.length, glossary.counts.terms);
  assert.equal(downloaded.terms[0].search, undefined);
  await page.selectOption('#locale', 'en');
  assert.equal(await page.locator('h1').innerText(), 'Complete glossary');
  await page.selectOption('#locale', 'fr');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(output, 'glossary-mobile.png') });
  assert.deepEqual(errors, []);
  console.log(`Glossary checks passed: ${glossary.counts.terms} terms, show-all, variants, filters, all four sections, role definitions, explorer links, URL state, CSV/JSON and FR/EN mobile.`);
} finally {
  await browser.close();
}
